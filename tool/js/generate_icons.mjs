// Regenerates packages/ui/src/ui/icons.ts from the Material Icons codepoints.
//
// The table holds every `Icons.*` name the shared UI uses (the Flutter
// client's names, so ported code keeps writing `Icons.mic_off_rounded`).
// Add a name to EXTRA_ICONS, or use it in lib/ or packages/ui/src, then run:
//   node tool/js/generate_icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const EXTRA_ICONS = [];

const scss = fs.readFileSync(path.join(root, 'node_modules/material-icons/css/_codepoints.scss'), 'utf8');
const codepoints = new Map([...scss.matchAll(/"([a-z0-9_]+)": ([0-9a-f]+)/g)].map((m) => [m[1], m[2]]));

function walk(dir, exts, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, exts, out);
    else if (exts.some((e) => entry.name.endsWith(e)) && entry.name !== 'icons.ts') out.push(full);
  }
  return out;
}

const names = new Set(EXTRA_ICONS);
for (const file of [...walk(path.join(root, 'lib'), ['.dart']), ...walk(path.join(root, 'packages/ui/src'), ['.ts', '.tsx'])]) {
  for (const m of fs.readFileSync(file, 'utf8').matchAll(/\bIcons\.([a-z][a-z0-9_]*)/g)) names.add(m[1]);
}

const variants = [
  ['_outlined', 'Material Icons Outlined'],
  ['_rounded', 'Material Icons Round'],
  ['_sharp', 'Material Icons Sharp'],
];
const rows = [];
for (const name of [...names].sort()) {
  let base = name;
  let family = 'Material Icons';
  for (const [suffix, fam] of variants) {
    if (name.endsWith(suffix)) {
      base = name.slice(0, -suffix.length);
      family = fam;
      break;
    }
  }
  const cp = codepoints.get(base);
  if (!cp) continue;
  rows.push(`  ${name}: icon(0x${cp}, '${family}'),`);
}

const source = `// GENERATED by tool/js/generate_icons.mjs — do not edit by hand.
//
// Material Icons used by the shared UI, keyed by their Flutter \`Icons.*\`
// names. Each entry names the icon font family and codepoint, which render the
// same through react-native-web (CSS @font-face) and React Native (bundled
// fonts registered under the same family names).

export interface IconData {
  readonly codePoint: number;
  readonly fontFamily: string;
}

function icon(codePoint: number, fontFamily: string): IconData {
  return { codePoint, fontFamily };
}

export const Icons = {
${rows.join('\n')}
} as const;

export type IconName = keyof typeof Icons;
`;
fs.writeFileSync(path.join(root, 'packages/ui/src/ui/icons.ts'), source);
console.log(`wrote ${rows.length} icons`);
